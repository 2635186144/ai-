import {test,expect} from '@playwright/test';

test('paragraph worksheet saves grounded facts, rejects fake quotes and resumes without a model',async({page})=>{
 test.setTimeout(45000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/?workspace=evidence&tools=1');
 const pending=page.waitForResponse(r=>r.url().endsWith('/api/v2/documents')&&r.request().method()==='POST');
 await page.locator('input[type=file]').setInputFiles('tests/fixtures/reading-sample.pdf');
 const doc=await(await pending).json();await expect(page.getByRole('status')).toContainText('原始文件已登记并保存');
 const base='/api/v2/documents/'+doc.id;
 let meta=await(await page.request.get(base)).json();
 if(!meta.extraction){await page.getByRole('button',{name:'解析结构',exact:true}).click();await expect(page.getByRole('region',{name:'章节与覆盖准备'})).toBeVisible();}
 // All confirmations below concern the synthetic fixture, never the real LoRA paper.
 let prep=await(await page.request.get(base+'/reading')).json();
 async function update(action,values={}){const r=await page.request.post(base+'/reading',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{revision:prep.revision,action,...values}});expect(r.ok()).toBeTruthy();prep=await r.json();}
 await update('set_sections',{sections:[prep.sections[0]]});
 for(const p of prep.pages)await update('confirm_page',{page:p.page,status:'confirmed'});
 for(const m of prep.materials)await update('mark_material',{material_id:m.id,status:'indexed'});
 await update('confirm_sections');
 await page.reload();
 await page.locator('.evidence-document[title="reading-sample.pdf"]').filter({hasText:'主论文'}).click();
 await page.getByRole('button',{name:'打开分节原文包',exact:true}).click();
 const sheet=page.getByRole('region',{name:'逐段事实底稿'});
 await expect(sheet.getByRole('heading',{name:'逐段读清，逐条留证。'})).toBeVisible();
 const nav=sheet.getByRole('navigation',{name:'原文单元清单'});
 await nav.getByRole('button').nth(1).click();
 const source=await sheet.locator('.fact-source>p').textContent();
 await sheet.getByLabel('本段解释',{exact:true}).fill('此段描述受控数据集这一实验设定。该记录针对测试夹具，尚未语义核验。');
 await expect(page.getByRole('combobox',{name:'分节材料包章节'})).toBeDisabled();
 await expect(page.locator('.evidence-document.selected')).toBeDisabled();
 await sheet.getByRole('button',{name:'添加事实条目',exact:true}).click();
 await sheet.getByLabel('事实 1 类型',{exact:true}).selectOption('experiment');
 await sheet.getByLabel('事实 1 陈述',{exact:true}).fill('测试原文说明方法使用受控数据集。');
 await sheet.getByLabel('事实 1 原文引文',{exact:true}).fill('This quotation is fabricated and absent.');
 await sheet.getByRole('button',{name:'保存本段底稿',exact:true}).click();
 await expect(sheet.getByRole('alert')).toContainText('逐字匹配');
 await sheet.getByLabel('事实 1 原文引文',{exact:true}).fill(source.slice(0,120));
 await sheet.getByRole('button',{name:'保存本段底稿',exact:true}).click();
 await expect(sheet.getByRole('status')).toContainText('本段记录已保存');
 await expect(sheet.locator('.fact-provenance')).toContainText('语义未核验');
 const exported=await sheet.getByRole('link',{name:'导出带来源的事实底稿'}).getAttribute('href');
 const data=JSON.parse(decodeURIComponent(exported.split(',').slice(1).join(',')));
 expect(data.units[1].draft.facts[0].category).toBe('experiment');
 expect(data.units[1].semantic_check).toBe('not_verified');
 expect(data.coverage.analysed).toBe(1);
 await sheet.getByRole('button',{name:'核对事实 1 的证据支持',exact:true}).click();
 const review=sheet.getByRole('region',{name:'事实 1 证据支持复核'});
 await review.getByLabel('分项 1 支持判断',{exact:true}).selectOption('partial');
 await review.getByLabel('分项 1 判断理由',{exact:true}).fill('合成测试：当前引文只支持部分表述，保留缺口，不声称语义验证通过。');
 await expect(page.getByRole('combobox',{name:'分节材料包章节'})).toBeDisabled();
 await review.getByRole('button',{name:'保存证据支持复核',exact:true}).click();
 await expect(review.getByRole('alert')).toContainText('必须关联已有引文');
 await review.getByLabel('分项 1 关联引文 1',{exact:true}).check();
 await review.getByRole('button',{name:'保存证据支持复核',exact:true}).click();
 await expect(sheet.getByRole('status')).toContainText('证据支持复核已记录');
 await expect(sheet.locator('.support-status')).toContainText('存在证据缺口或矛盾');
 if(!data.model.configured)await expect(sheet.getByRole('button',{name:'生成本段事实底稿',exact:true})).toBeDisabled();
 await sheet.screenshot({path:'test-results/paragraph-facts-desktop.png'});
 await page.reload();await page.locator('.evidence-document[title="reading-sample.pdf"]').filter({hasText:'主论文'}).click();
 await page.getByRole('button',{name:'打开分节原文包',exact:true}).click();
 await nav.getByRole('button').nth(1).click();
 await expect(sheet.getByLabel('事实 1 陈述',{exact:true})).toHaveValue('测试原文说明方法使用受控数据集。');
 await expect(sheet.locator('.support-status')).toContainText('存在证据缺口或矛盾');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await sheet.screenshot({path:'test-results/paragraph-facts-mobile.png'});
 await sheet.getByRole('button',{name:'核对事实 1 的证据支持',exact:true}).click();
 await expect(sheet.getByRole('region',{name:'事实 1 证据支持复核'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await sheet.getByRole('region',{name:'事实 1 证据支持复核'}).screenshot({path:'test-results/support-review-mobile.png'});
 expect(errors).toEqual([]);
});
